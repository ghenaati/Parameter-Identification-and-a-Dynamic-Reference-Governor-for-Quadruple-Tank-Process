function hprim=QTP(t,h)
%%-------------------------------------------------
global gama1 gama2 K1 K2 A1 A2 A3 A4 a1 a2 a3 a4 g V1 V2;
%%-------------------------------------------------
hprim=zeros(4,1);
hprim(1)=-a1*sqrt(2*g*h(1))/A1...
         +a3*sqrt(2*g*h(3))/A1...
         +gama1*K1*V1/A1;
hprim(2)=-a2*sqrt(2*g*h(2))/A2...
         +a4*sqrt(2*g*h(4))/A2...
         +gama2*K2*V2/A2;
hprim(3)=-a3*sqrt(2*g*h(3))/A3...
         +(1-gama2)*K2*V2/A3;
hprim(4)=-a4*sqrt(2*g*h(4))/A4...
         +(1-gama1)*K1*V1/A4;
hprim=real(hprim); % to avoid numerical errors we removed imaginary part which is zero.
end